def _get_installment_balance(
    db: TenantSession,
    installment: PaymentInstallment,
) -> Decimal:
    payments_total = db.scalar(
        select(
            func.coalesce(func.sum(Payment.amount), Decimal("0"))
        ).where(
            Payment.installment_id == installment.id,
        )
    ) or Decimal("0")

    completed_refunds = db.scalar(
        select(
            func.coalesce(func.sum(PaymentRefund.amount), Decimal("0"))
        )
        .join(
            Payment,
            PaymentRefund.payment_id == Payment.id,
        )
        .where(
            Payment.installment_id == installment.id,
            PaymentRefund.status == PaymentRefundStatus.COMPLETED,
        )
    ) or Decimal("0")

    discounts_total = db.scalar(
        select(
            func.coalesce(
                func.sum(EventFinancialAdjustmentAllocation.allocated_amount),
                Decimal("0"),
            )
        ).where(
            EventFinancialAdjustmentAllocation.installment_id
            == installment.id,
        )
    ) or Decimal("0")

    balance = (
        installment.amount
        - payments_total
        + completed_refunds
        - discounts_total
    )

    return max(balance, Decimal("0"))


def _update_installment_status(
    installment: PaymentInstallment,
    balance: Decimal,
) -> None:
    if installment.status == InstallmentStatus.CANCELLED:
        return

    if balance == Decimal("0"):
        installment.status = InstallmentStatus.PAID
    elif balance < installment.amount:
        installment.status = InstallmentStatus.PARTIALLY_PAID
    else:
        installment.status = InstallmentStatus.PENDING


def _create_discount_refunds(
    db: TenantSession,
    adjustment: EventFinancialAdjustment,
    event_id: UUID,
    refund_amount: Decimal,
    recorded_by_user_id: UUID,
) -> None:
    if refund_amount <= Decimal("0"):
        return

    payments = list(
        db.scalars(
            select(Payment)
            .join(
                PaymentInstallment,
                Payment.installment_id == PaymentInstallment.id,
            )
            .join(
                PaymentSchedule,
                PaymentInstallment.payment_schedule_id
                == PaymentSchedule.id,
            )
            .where(PaymentSchedule.event_id == event_id)
            .order_by(Payment.received_at.desc(), Payment.id)
            .with_for_update()
        ).all()
    )

    remaining = refund_amount

    for payment in payments:
        reserved = db.scalar(
            select(
                func.coalesce(
                    func.sum(PaymentRefund.amount),
                    Decimal("0"),
                )
            ).where(
                PaymentRefund.payment_id == payment.id,
                PaymentRefund.status != PaymentRefundStatus.CANCELLED,
            )
        ) or Decimal("0")

        available = max(
            payment.amount - reserved,
            Decimal("0"),
        )

        if available <= Decimal("0"):
            continue

        amount = min(available, remaining)

        db.add(
            PaymentRefund(
                tenant_id=payment.tenant_id,
                payment_id=payment.id,
                financial_adjustment_id=adjustment.id,
                amount=amount,
                refund_method=payment.payment_method,
                status=PaymentRefundStatus.PENDING,
                reason=f"Refund generated by discount: {adjustment.reason}",
                recorded_by_user_id=recorded_by_user_id,
            )
        )

        remaining -= amount

        if remaining == Decimal("0"):
            break

    if remaining > Decimal("0"):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail=(
                "The discount exceeds the outstanding balance, but "
                "the received payments do not have enough refundable "
                f"amount. Uncovered refund amount: {remaining}."
            ),
        )


def create_financial_adjustment(
    db: TenantSession,
    data: EventFinancialAdjustmentCreate,
    recorded_by_user_id: UUID,
) -> EventFinancialAdjustment:
    try:
        event = db.scalar(
            select(Event)
            .where(Event.id == data.event_id)
            .with_for_update()
        )

        if event is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Event not found.",
            )

        schedule = db.scalar(
            select(PaymentSchedule)
            .where(PaymentSchedule.event_id == event.id)
            .with_for_update()
        )

        if schedule is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Payment schedule not found for this event.",
            )

        if schedule.status != PaymentScheduleStatus.ACTIVE:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Cannot adjust an inactive payment schedule.",
            )

        installments = payment_installments.list_by_schedule_id(
            db,
            schedule.id,
            for_update=True,
        )

        if data.adjustment_type == FinancialAdjustmentType.ADDITIONAL:
            next_number = (
                payment_installments.get_next_installment_number(
                    db,
                    schedule.id,
                )
            )

            installment = PaymentInstallment(
                tenant_id=event.tenant_id,
                payment_schedule_id=schedule.id,
                installment_number=next_number,
                installment_type=InstallmentType.FIXED,
                amount=data.amount,
                percentage=None,
                due_date=data.due_date,
                status=InstallmentStatus.PENDING,
            )

            payment_installments.create(
                db,
                installment,
            )
            db.flush()

            adjustment = EventFinancialAdjustment(
                tenant_id=event.tenant_id,
                event_id=event.id,
                adjustment_type=FinancialAdjustmentType.ADDITIONAL,
                amount=data.amount,
                reason=data.reason,
                recorded_by_user_id=recorded_by_user_id,
                created_installment_id=installment.id,
            )

            event_financial_adjustments.create(
                db,
                adjustment,
            )

        elif data.adjustment_type == FinancialAdjustmentType.DISCOUNT:
            adjustment = EventFinancialAdjustment(
                tenant_id=event.tenant_id,
                event_id=event.id,
                adjustment_type=FinancialAdjustmentType.DISCOUNT,
                amount=data.amount,
                reason=data.reason,
                recorded_by_user_id=recorded_by_user_id,
            )

            event_financial_adjustments.create(
                db,
                adjustment,
            )

            remaining_discount = data.amount

            eligible_installments = sorted(
                (
                    installment
                    for installment in installments
                    if installment.status != InstallmentStatus.CANCELLED
                ),
                key=lambda installment: (
                    installment.due_date,
                    installment.installment_number,
                ),
                reverse=True,
            )

            for installment in eligible_installments:
                if remaining_discount <= Decimal("0"):
                    break

                outstanding = _get_installment_balance(
                    db,
                    installment,
                )

                if outstanding <= Decimal("0"):
                    continue

                allocated_amount = min(
                    outstanding,
                    remaining_discount,
                )

                allocation = EventFinancialAdjustmentAllocation(
                    tenant_id=event.tenant_id,
                    adjustment_id=adjustment.id,
                    installment_id=installment.id,
                    allocated_amount=allocated_amount,
                )

                db.add(allocation)
                db.flush()

                remaining_discount -= allocated_amount

                updated_balance = outstanding - allocated_amount

                _update_installment_status(
                    installment,
                    updated_balance,
                )

            if remaining_discount > Decimal("0"):
                _create_discount_refunds(
                    db,
                    adjustment,
                    event.id,
                    remaining_discount,
                    recorded_by_user_id,
                )

        else:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
                detail="Unsupported financial adjustment type.",
            )

        db.commit()

        return event_financial_adjustments.get_by_id(
            db,
            adjustment.id,
            with_allocations=True,
        )

    except HTTPException:
        db.rollback()
        raise

    except IntegrityError as exc:
        db.rollback()
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Could not create the financial adjustment.",
        ) from exc

    except Exception:
        db.rollback()
        raise


def get_financial_adjustment(
    db: TenantSession,
    adjustment_id: UUID,
) -> EventFinancialAdjustment:
    adjustment = event_financial_adjustments.get_by_id(
        db,
        adjustment_id,
        with_allocations=True,
    )

    if adjustment is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Financial adjustment not found.",
        )

    return adjustment


def list_financial_adjustments_by_event(
    db: TenantSession,
    event_id: UUID,
) -> list[EventFinancialAdjustment]:
    return event_financial_adjustments.list_by_event_id(
        db,
        event_id,
        with_allocations=True,
    )
